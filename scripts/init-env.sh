#!/usr/bin/env bash
# Generates the .env of a local stack: every secret is random, and the payment-order signing key
# pair is created for this workstation. Refuses to overwrite an existing .env (secrets already
# baked into the PostgreSQL volume would no longer match): remove it with the volumes first
# (docker compose down -v).
#
# Requires openssl (bundled with Git for Windows).
#
#   ./scripts/init-env.sh [path/to/.env]
set -euo pipefail

target="${1:-$(dirname "$0")/../.env}"
if [ -e "$target" ]; then
  echo "$target already exists, nothing done." >&2
  exit 1
fi

secret() { openssl rand -hex 24; }
# Satisfies the Keycloak password policy of the realm (upper, lower, digit, special, 12+).
demo_password() { echo "Atlas-$(openssl rand -hex 8)-Demo!"; }

key_file="$(mktemp)"
trap 'rm -f "$key_file"' EXIT
openssl genpkey -algorithm ed25519 -outform DER -out "$key_file" 2>/dev/null
private_key="$(base64 < "$key_file" | tr -d '\n')"
public_key="$(openssl pkey -inform DER -in "$key_file" -pubout -outform DER | base64 | tr -d '\n')"

umask 077
cat > "$target" <<EOF
# Generated by scripts/init-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Local secrets: never commit them.
POSTGRES_PASSWORD=$(secret)
CUSTOMER_DB_OWNER_PASSWORD=$(secret)
CUSTOMER_DB_PASSWORD=$(secret)
ACCOUNT_DB_OWNER_PASSWORD=$(secret)
ACCOUNT_DB_PASSWORD=$(secret)
TRANSACTION_DB_OWNER_PASSWORD=$(secret)
TRANSACTION_DB_PASSWORD=$(secret)
NOTIFICATION_DB_OWNER_PASSWORD=$(secret)
NOTIFICATION_DB_PASSWORD=$(secret)
KEYCLOAK_DB_PASSWORD=$(secret)

KAFKA_ADMIN_PASSWORD=$(secret)
KAFKA_CUSTOMER_SERVICE_PASSWORD=$(secret)
KAFKA_ACCOUNT_SERVICE_PASSWORD=$(secret)
KAFKA_TRANSACTION_SERVICE_PASSWORD=$(secret)
KAFKA_NOTIFICATION_SERVICE_PASSWORD=$(secret)

ATLAS_ORDER_SIGNING_KEY_ID=local-$(date -u +%Y%m%d)
ATLAS_ORDER_SIGNING_PRIVATE_KEY=$private_key
ATLAS_ORDER_SIGNING_PUBLIC_KEY=$public_key

KEYCLOAK_ADMIN_PASSWORD=$(secret)
ATLAS_CUSTOMER_SERVICE_CLIENT_SECRET=$(secret)
ATLAS_DEMO_ADMIN_PASSWORD=$(demo_password)
ATLAS_DEMO_EMPLOYEE_PASSWORD=$(demo_password)

ATLAS_PII_ENCRYPTION_PASSWORD=$(secret)
ATLAS_PII_ENCRYPTION_SALT=$(openssl rand -hex 16)
ATLAS_PII_FINGERPRINT_KEY=$(openssl rand -hex 32)

REDIS_PASSWORD=$(secret)
EOF
echo "Wrote $target"
