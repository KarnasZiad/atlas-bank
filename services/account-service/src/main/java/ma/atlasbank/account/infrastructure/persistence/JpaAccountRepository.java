package ma.atlasbank.account.infrastructure.persistence;

import jakarta.persistence.LockModeType;
import java.util.Optional;
import java.util.UUID;
import ma.atlasbank.account.application.AccountSearchCriteria;
import ma.atlasbank.account.application.port.AccountRepository;
import ma.atlasbank.account.domain.Account;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.JpaSpecificationExecutor;
import org.springframework.data.jpa.repository.Lock;

interface JpaAccountRepository extends JpaRepository<Account, UUID>, JpaSpecificationExecutor<Account>, AccountRepository {

    /** {@code SELECT ... FOR UPDATE}, generated by Hibernate from the JPA lock mode. */
    @Lock(LockModeType.PESSIMISTIC_WRITE)
    Optional<Account> findForUpdateByAccountNumber(String accountNumber);

    @Override
    default Optional<Account> lockByAccountNumber(String accountNumber) {
        return findForUpdateByAccountNumber(accountNumber);
    }

    @Override
    default Page<Account> search(AccountSearchCriteria criteria, Pageable pageable) {
        return findAll(AccountSpecifications.matching(criteria), pageable);
    }
}
